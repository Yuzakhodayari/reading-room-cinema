export function findSetPieceBlueprint(idOrQuery: string): SceneBlueprint | undefined {
  if (!idOrQuery) return undefined;
  const trimmed = idOrQuery.trim();
  if (!trimmed) return undefined;

  if (SET_PIECE_ALIAS_MAP[trimmed]) return SET_PIECE_ALIAS_MAP[trimmed];
  const lower = trimmed.toLowerCase();
  if (SET_PIECE_ALIAS_MAP[lower]) return SET_PIECE_ALIAS_MAP[lower];
  const kebab = lower.replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
  if (SET_PIECE_ALIAS_MAP[kebab]) return SET_PIECE_ALIAS_MAP[kebab];

  // Deterministic lexical token scoring across id, title, subtitle, and actor headlines
  const tokens = lower.split(/[^a-z0-9.%$]+/).filter((t) => t.length >= 2);
  if (tokens.length === 0) return undefined;

  let bestBp: SceneBlueprint | undefined;
  let bestScore = 0;

  for (let i = 0; i < PRESET_SET_PIECE_LIST.length; i++) {
    const bp = PRESET_SET_PIECE_LIST[i];
    const corpusParts: string[] = [
      bp.id,
      bp.title,
      bp.subtitle ?? "",
      bp.polish?.mastheadTitle ?? "",
      bp.polish?.sourceCitation ?? "",
    ];
    for (let a = 0; a < bp.actors.length; a++) {
      const act = bp.actors[a];
      corpusParts.push(act.id);
      if (act.propRig) corpusParts.push(act.propRig.headline, act.propRig.metricText ?? "");
      if (act.metricCounter) corpusParts.push(act.metricCounter.label, act.metricCounter.deltaBadge ?? "");
      if (act.documentCard) corpusParts.push(act.documentCard.title);
      if (act.verdictStamp) corpusParts.push(act.verdictStamp.stampText);
    }
    const haystack = corpusParts.join(" ").toLowerCase();

    let score = 0;
    for (let t = 0; t < tokens.length; t++) {
      const tok = tokens[t];
      if (bp.id.toLowerCase().indexOf(tok) !== -1) score += 18;
      if (bp.title.toLowerCase().indexOf(tok) !== -1) score += 12;
      if (haystack.indexOf(tok) !== -1) score += 5;
    }

    if (score > bestScore) {
      bestScore = score;
      bestBp = bp;
    }
  }

  return bestScore > 0 ? bestBp : undefined;
}

/**
 * Resolves a preset Set-Piece SceneBlueprint by constant key (`SP01_...`), blueprint ID,
 * Season-1 roadmap slug (`sp-ep03-nvidia-coreweave-spv-carousel`), or semantic query.
 * Deterministically falls back to `SP01_SHOE_LABOR_VAPORIZER` when unmatched.
 */
export function resolveSetPieceBlueprint(idOrQuery?: string): SceneBlueprint {
  if (!idOrQuery) return SP01_SHOE_LABOR_VAPORIZER;
  return findSetPieceBlueprint(idOrQuery) ?? SP01_SHOE_LABOR_VAPORIZER;
}
